def build_coverage_report(conn: sqlite3.Connection) -> dict[str, Any]:
    items = coverage_items()
    status_counts = {status: 0 for status in STATUS_WEIGHTS}
    for item_data in items:
        status_counts[str(item_data["status"])] += 1

    status_weighted = sum(STATUS_WEIGHTS[str(item_data["status"])] for item_data in items)
    weighted = sum(float(item_data.get("maturity_score", STATUS_WEIGHTS[str(item_data["status"])])) for item_data in items)
    max_score = len(items) or 1
    coverage_score = weighted / max_score
    coarse_status_score = status_weighted / max_score
    status_progress_score = (coverage_score + coarse_status_score) / 2.0
    blocked = [item_data for item_data in items if item_data["status"] in {STATUS_MISSING, STATUS_EXTERNAL}]
    priority_items = sorted(
        blocked,
        key=lambda item_data: (int(item_data["priority"]), int(item_data["id"])),
    )[:8]

    return {
        "title": "方程式覆蓋率 / 盲點報告",
        "objective": "以 36 個賽馬方程式主項追蹤模型補洞進度；所有補洞都要用 walk-forward / out-of-sample 證明提升。",
        "status_labels": {
            "done": STATUS_DONE,
            "partial": STATUS_PARTIAL,
            "missing": STATUS_MISSING,
            "external": STATUS_EXTERNAL,
        },
        "summary": {
            "target_groups": 36,
            "total_groups": len(items),
            "core_groups": sum(1 for item_data in items if item_data["category"] == "core"),
            "blind_spot_groups": sum(1 for item_data in items if item_data["category"] == "advanced"),
            "coverage_score": round(coverage_score, 4),
            "status_coverage_score": round(status_progress_score, 4),
            "coarse_status_score": round(coarse_status_score, 4),
            "coverage_score_method": "覆蓋分以每項 maturity_score 計算；狀態進度分會混合粗分類與 maturity，所以每次有實質模型補洞都會同步變動；粗分類基準只在已完成/部分完成等大狀態改變時變動。",
            "status_counts": status_counts,
            "database": database_snapshot(conn),
        },
        "items": items,
        "priority_next_steps": [
            {
                "id": item_data["id"],
                "name": item_data["name"],
                "status": item_data["status"],
                "model_risk": item_data["model_risk"],
                "next_steps": item_data["next_steps"],
                "validation_gate": item_data["validation_gate"],
            }
            for item_data in priority_items
        ],
    }


def database_snapshot(conn: sqlite3.Connection) -> dict[str, int]:
    tables = [
        "races",
        "runners",
        "results",
        "workouts",
        "odds_ticks",
        "raw_snapshots",
        "race_status",
        "model_registry_runs",
        "betting_recommendations",
        "exotic_dividends",
    ]
    snapshot: dict[str, int] = {}
    for table in tables:
        try:
            snapshot[table] = int(fetch_all(conn, f"SELECT count(*) AS n FROM {table}")[0]["n"])
        except sqlite3.Error:
            snapshot[table] = 0
    return snapshot


