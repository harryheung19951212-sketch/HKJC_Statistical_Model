STATUS_DONE = "已完成"
STATUS_PARTIAL = "部分完成"
STATUS_MISSING = "未完成"
STATUS_EXTERNAL = "需要外部數據"

STATUS_WEIGHTS = {
    STATUS_DONE: 1.0,
    STATUS_PARTIAL: 0.5,
    STATUS_EXTERNAL: 0.15,
    STATUS_MISSING: 0.0,
}


def build_coverage_report(conn: sqlite3.Connection) -> dict[str, Any]:
    items = coverage_items()
    status_counts = {status: 0 for status in STATUS_WEIGHTS}
    for item in items:
        status_counts[str(item["status"])] += 1

    weighted = sum(STATUS_WEIGHTS[str(item["status"])] for item in items)
    max_score = len(items) or 1
    blocked = [item for item in items if item["status"] in {STATUS_MISSING, STATUS_EXTERNAL}]
    priority_items = sorted(
        blocked,
        key=lambda item: (int(item["priority"]), int(item["id"])),
    )[:8]

    return {
        "title": "方程式覆蓋率 / 盲點報告",
        "objective": "用來定位模型缺口，所有補洞都要用 walk-forward / out-of-sample 證明提升。",
        "status_labels": {
            "done": STATUS_DONE,
            "partial": STATUS_PARTIAL,
            "missing": STATUS_MISSING,
            "external": STATUS_EXTERNAL,
        },
        "summary": {
            "total_groups": len(items),
            "core_groups": sum(1 for item in items if item["category"] == "core"),
            "blind_spot_groups": sum(1 for item in items if item["category"] == "blind_spot"),
            "coverage_score": round(weighted / max_score, 4),
            "status_counts": status_counts,
            "database": database_snapshot(conn),
        },
        "items": items,
        "priority_next_steps": [
            {
                "id": item["id"],
                "name": item["name"],
                "status": item["status"],
                "model_risk": item["model_risk"],
                "next_steps": item["next_steps"],
                "validation_gate": item["validation_gate"],
            }
            for item in priority_items
        ],
    }


def database_snapshot(conn: sqlite3.Connection) -> dict[str, int]:
    tables = ["races", "runners", "results", "workouts", "odds_ticks", "raw_snapshots", "race_status"]
    snapshot: dict[str, int] = {}
    for table in tables:
        try:
            snapshot[table] = int(fetch_all(conn, f"SELECT count(*) AS n FROM {table}")[0]["n"])
        except sqlite3.Error:
            snapshot[table] = 0
    return snapshot


