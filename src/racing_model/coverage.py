def item(
    item_id: int,
    category: str,
    name: str,
    status: str,
    data_sources: list[str],
    supported_files: list[str],
    current_support: str,
    gaps: str,
    next_steps: str,
    sub_items: list[str],
    model_risk: str,
    validation_gate: str,
    priority: int,
) -> dict[str, Any]:
    default_score = STATUS_WEIGHTS[status]
    override_score, override_reason = MATURITY_OVERRIDES.get(item_id, (default_score, "按目前狀態權重計算。"))
    maturity_score = max(0.0, min(float(override_score), STATUS_WEIGHTS[STATUS_DONE]))
    return {
        "id": item_id,
        "category": category,
        "category_label": "核心方程式主項" if category == "core" else "進階實戰主項",
        "name": name,
        "status": status,
        "status_key": status_key(status),
        "maturity_score": round(maturity_score, 4),
        "maturity_percent": round(maturity_score * 100, 1),
        "maturity_reason": override_reason,
        "data_sources": data_sources,
        "supported_files": supported_files,
        "current_support": current_support,
        "gaps": gaps,
        "next_steps": next_steps,
        "sub_items": sub_items,
        "model_risk": model_risk,
        "validation_gate": validation_gate,
        "priority": priority,
    }


def status_key(status: str) -> str:
    return {
        STATUS_DONE: "done",
        STATUS_PARTIAL: "partial",
        STATUS_MISSING: "missing",
        STATUS_EXTERNAL: "external",
    }[status]
